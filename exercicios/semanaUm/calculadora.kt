fun main() {
    val n1 = 30
    val n2 = 20
    println("Primeiro numero inserido: $n1")
    println("Segundo numero inserido: $n2")
    println("Resultado da soma: ${n1 + n2}")
    println("Resultado da subtração: ${n1 - n2}")
    println("Resultado da multiplicação: ${n1 * n2}")
    println("Resultado da divisão: ${n1 / n2}")
    println("Resultado do resto da divisão: ${n1 % n2}")
}